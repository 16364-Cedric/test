package fr.dati.core

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

class DeploymentConfigTest {
    @Test
    fun `parses a link generated by the supervision console`() {
        val config = DeploymentConfig.fromQuery(
            "server=https%3A%2F%2Fdati.example%2F&token=abc123&name=Chlo%C3%A9+Petit" +
                "&contacts=%2B33612345678%2C06+12+34+56+78&checkin=30&prealarm=45&immobility=0&sensitivity=HIGH"
        )
        assertEquals("https://dati.example", config.serverUrl)
        assertEquals("abc123", config.token)
        assertEquals("Chloé Petit", config.userName)
        assertEquals(listOf("+33612345678", "0612345678"), config.contacts)
        assertEquals(30, config.checkInMinutes)
        assertEquals(45, config.preAlarmSeconds)
        assertEquals(0, config.immobilitySeconds)
        assertEquals(FallSensitivity.HIGH, config.fallSensitivity)
        assertNull(config.fallDetection)
    }

    @Test
    fun `booleans accept french and numeric forms`() {
        val config = DeploymentConfig.fromMap(mapOf("fall" to "non", "call" to "1", "powersos" to "Oui"))
        assertEquals(false, config.fallDetection)
        assertEquals(true, config.callFirstContact)
        assertEquals(true, config.powerButtonSos)
    }

    @Test
    fun `unencrypted servers are refused`() {
        assertFailsWith<IllegalArgumentException> { DeploymentConfig.fromQuery("server=http%3A%2F%2Fevil.example") }
    }

    @Test
    fun `invalid values are refused`() {
        assertFailsWith<IllegalArgumentException> { DeploymentConfig.fromQuery("contacts=abc") }
        assertFailsWith<IllegalArgumentException> { DeploymentConfig.fromQuery("prealarm=3") }
        assertFailsWith<IllegalArgumentException> { DeploymentConfig.fromQuery("checkin=soon") }
        assertFailsWith<IllegalArgumentException> { DeploymentConfig.fromQuery("sensitivity=MAX") }
    }

    @Test
    fun `empty query gives an empty config`() {
        assertTrue(DeploymentConfig.fromQuery("").isEmpty)
        assertTrue(DeploymentConfig.fromMap(mapOf("name" to "  ")).isEmpty)
    }

    @Test
    fun `phone numbers are normalised`() {
        assertEquals("+33612345678", PhoneNumbers.normalize("+33 6.12-34 56 78"))
        assertNull(PhoneNumbers.normalize("12"))
        assertNull(PhoneNumbers.normalize("06 12 AB"))
    }

    @Test
    fun `reads both link forms`() {
        assertEquals("t1", DeploymentConfig.fromLink("dati://config?token=t1").token)
        assertEquals("t2", DeploymentConfig.fromLink(" https://dati.example/c#token=t2&name=A ").token)
        assertFailsWith<IllegalArgumentException> { DeploymentConfig.fromLink("bonjour") }
    }
}
